// these icons aren't scanned and bundled automatically
export const selectableIcons: {
	normalName: string // without prefix
	prettyName: string
	id: string
}[] = []

mingCuteIcons.forEach((k) => {
	const name = k.replace("mingcute:", "")
	selectableIcons.push({
		normalName: name,
		prettyName: name.replace(/-fill$/, "").replaceAll("-", " "),
		id: k,
	})
})

export function selectableIconList() {
	return selectableIcons.map((v) => {
		return v.id
	})
}
